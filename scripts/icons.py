"""Icon font with only the Phosphor icons the app uses (performance audit, 25 Oct 2026): ~5 KB instead of 206 KB.

Run after using a new icon (npm run icons), then commit app/icons/. npm test fails while a ph-* class in app/
or lib/ is missing from app/icons/phosphor.css. Needs Python with fonttools and brotli (pip install fonttools brotli).
"""
import pathlib
import re

from fontTools import subset

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / 'node_modules/@phosphor-icons/web/src/regular'
OUT = ROOT / 'app/icons'

css = (SRC / 'style.css').read_text(encoding='utf-8')
rules = dict(re.findall(r'\.ph\.(ph-[a-z0-9-]+):before \{\s*content: "\\([0-9a-f]+)";\s*\}', css))
used = set()
for f in [*ROOT.glob('app/**/*.js'), *ROOT.glob('app/**/*.css'), *ROOT.glob('lib/**/*.js')]:
    if OUT not in f.parents:
        used.update(re.findall(r'\bph-[a-z0-9-]+', f.read_text(encoding='utf-8')))
icons = sorted(n for n in used if n in rules)

opts = subset.Options()
opts.flavor = 'woff2'
opts.layout_features = []  # the stylesheet picks icons by code point; the name ligatures aren't needed
font = subset.load_font(str(SRC / 'Phosphor.ttf'), opts)
sub = subset.Subsetter(opts)
sub.populate(unicodes=[int(rules[n], 16) for n in icons])
sub.subset(font)
OUT.mkdir(exist_ok=True)
subset.save_font(font, str(OUT / 'phosphor.woff2'), opts)

face = '@font-face {\n  font-family: "Phosphor";\n  src: url("./phosphor.woff2") format("woff2");\n  font-weight: normal;\n  font-style: normal;\n  font-display: block;\n}\n\n'
base = css[css.index('.ph {'):css.index('.ph.ph-')]
glyphs = ''.join(f'.ph.{n}:before {{ content: "\\{rules[n]}"; }}\n' for n in icons)
note = f'/* Generated by scripts/icons.py ({len(icons)} of {len(rules)} Phosphor icons). Do not edit: run npm run icons. */\n'
(OUT / 'phosphor.css').write_text(note + face + base + glyphs, encoding='utf-8', newline='\n')
print(f'{len(icons)} icons, {(OUT / "phosphor.woff2").stat().st_size} bytes')
