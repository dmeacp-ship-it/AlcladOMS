# One-off: turns the Ref files xlsx masters into supabase/seed.sql.
# Run from the tas-oms folder:  python supabase/make_seed.py
import openpyxl

REF = "../Ref files/"


def q(v):
    if v is None or str(v).strip() in ("", "-", "NA"):
        return "null"
    return "'" + str(v).strip().replace("'", "''") + "'"


out = ["-- Generated by supabase/make_seed.py from 'Ref files'. Run once, after schema.sql."]

ws = openpyxl.load_workbook(REF + "Supplier List.xlsx", read_only=True, data_only=True).worksheets[0]
rows = [r for r in ws.iter_rows(min_row=2, values_only=True) if r[0]]
out.append("insert into customers (code, name, type, country, vat_no, address) values")
out.append(",\n".join(
    f"({q(f'CUS-{i:03d}')}, {q(r[0])}, {q(r[1])}, {q(r[2])}, {q(r[3])}, {q(r[4])})"
    for i, r in enumerate(rows, 1)) + "\non conflict (name) do nothing;")

ws = openpyxl.load_workbook(REF + "RM-Finish Goods SKU.xlsx", read_only=True, data_only=True)["Finish Goods SKU"]
rows = [r[:11] for r in ws.iter_rows(min_row=4, values_only=True) if r[0]]
out.append("insert into items (brand, color_code, color_name, grade, core, skin, width, length, thickness, description, uom) values")
out.append(",\n".join("(" + ", ".join(q(v) for v in r) + ")" for r in rows) + ";")

open("supabase/seed.sql", "w", encoding="utf-8").write("\n".join(out) + "\n")
print("customers + items written to supabase/seed.sql")
